// SQL the tree's context menus write. Every statement runs through the
// normal query path, so grants, production confirmation and the query log
// apply to it like to anything typed in the editor.

import { qualified, quoteIdent } from '@/lib/stores/workspace.svelte';

export function selectSQL(dbType: string, schema: string, table: string, limit = 100): string {
  const from = qualified(dbType, schema, table);
  if (dbType === 'mssql') return `SELECT TOP (${limit}) *\nFROM ${from};`;
  if (dbType === 'oracle' || dbType === 'odbc') return `SELECT *\nFROM ${from}\nFETCH FIRST ${limit} ROWS ONLY;`;
  return `SELECT *\nFROM ${from}\nLIMIT ${limit};`;
}

export function countSQL(dbType: string, schema: string, table: string): string {
  return `SELECT COUNT(*)\nFROM ${qualified(dbType, schema, table)};`;
}

export function insertSQL(dbType: string, schema: string, table: string, columns: string[]): string {
  const cols = columns.length ? columns : ['column1'];
  return `INSERT INTO ${qualified(dbType, schema, table)} (${cols.map((c) => quoteIdent(dbType, c)).join(', ')})\nVALUES (${cols.map(() => '?').join(', ')});`;
}

export function createTableSQL(dbType: string, schema: string): string {
  const name = qualified(dbType, schema, 'new_table');
  const id =
    dbType === 'mssql'
      ? 'id INT IDENTITY PRIMARY KEY'
      : dbType === 'oracle'
        ? 'id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : dbType === 'mysql' || dbType === 'mariadb'
          ? 'id BIGINT AUTO_INCREMENT PRIMARY KEY'
          : dbType === 'sqlite'
            ? 'id INTEGER PRIMARY KEY'
            : dbType === 'clickhouse'
              ? 'id UInt64'
              : 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
  const text = dbType === 'oracle' ? 'VARCHAR2(200)' : dbType === 'clickhouse' ? 'String' : 'VARCHAR(200)';
  const engine = dbType === 'clickhouse' ? '\nENGINE = MergeTree\nORDER BY id' : '';
  return `CREATE TABLE ${name} (\n  ${id},\n  name ${text} NOT NULL\n)${engine};`;
}

export function createSchemaSQL(dbType: string): string {
  if (dbType === 'mysql' || dbType === 'mariadb' || dbType === 'clickhouse') return 'CREATE DATABASE new_database;';
  if (dbType === 'oracle') return '-- Oracle schemas are users:\nCREATE USER new_schema IDENTIFIED BY "change-me";';
  return 'CREATE SCHEMA new_schema;';
}

export function dropTableSQL(dbType: string, schema: string, table: string, kind: string): string {
  const what = kind === 'view' ? 'VIEW' : kind === 'materialized_view' ? 'MATERIALIZED VIEW' : 'TABLE';
  return `DROP ${what} ${qualified(dbType, schema, table)};`;
}

// emptySQL deletes every row one by one: slower than TRUNCATE, but it runs
// triggers, respects foreign keys and can be rolled back everywhere.
export function emptySQL(dbType: string, schema: string, table: string): string {
  if (dbType === 'clickhouse') return `ALTER TABLE ${qualified(dbType, schema, table)} DELETE WHERE 1;`;
  return `DELETE FROM ${qualified(dbType, schema, table)};`;
}

export function truncateSQL(dbType: string, schema: string, table: string): string {
  if (dbType === 'sqlite') return `DELETE FROM ${qualified(dbType, schema, table)};`;
  return `TRUNCATE TABLE ${qualified(dbType, schema, table)};`;
}

export function renameTableSQL(dbType: string, schema: string, table: string, to: string): string {
  const from = qualified(dbType, schema, table);
  if (dbType === 'mssql') return `EXEC sp_rename '${(schema ? schema + '.' : '') + table}', '${to.replaceAll("'", "''")}';`;
  if (dbType === 'mysql' || dbType === 'mariadb' || dbType === 'clickhouse') return `RENAME TABLE ${from} TO ${qualified(dbType, schema, to)};`;
  return `ALTER TABLE ${from} RENAME TO ${quoteIdent(dbType, to)};`;
}

export function dropSchemaSQL(dbType: string, schema: string): string {
  const name = quoteIdent(dbType, schema);
  if (dbType === 'mysql' || dbType === 'mariadb' || dbType === 'clickhouse') return `DROP DATABASE ${name};`;
  if (dbType === 'oracle') return `DROP USER ${name} CASCADE;`;
  return `DROP SCHEMA ${name};`;
}

export function dropRoutineSQL(dbType: string, schema: string, name: string, kind: string, signature = ''): string {
  const what = kind.toUpperCase();
  const sig = dbType === 'postgres' && kind !== 'sequence' ? signature : '';
  return `DROP ${what} ${qualified(dbType, schema, name)}${sig};`;
}

export function callSQL(dbType: string, schema: string, name: string, kind: string): string {
  const q = qualified(dbType, schema, name);
  if (kind === 'sequence') {
    if (dbType === 'oracle') return `SELECT ${q}.NEXTVAL FROM dual;`;
    if (dbType === 'mssql') return `SELECT NEXT VALUE FOR ${q};`;
    return `SELECT nextval('${(schema ? schema + '.' : '') + name}');`;
  }
  if (kind === 'procedure') {
    if (dbType === 'mssql') return `EXEC ${q};`;
    if (dbType === 'oracle') return `BEGIN\n  ${q};\nEND;`;
    return `CALL ${q}();`;
  }
  if (dbType === 'oracle') return `SELECT ${q}() FROM dual;`;
  return `SELECT ${q}();`;
}

// Databases without schemas or with one fixed schema cannot create or drop
// one from the tree.
export function hasSchemas(dbType: string): boolean {
  return !['sqlite', 'trino'].includes(dbType);
}

// useSchemaSQL starts a new query in the schema, as a comment where the
// database has no statement for it, so nothing runs by accident.
export function useSchemaSQL(dbType: string, schema: string): string {
  const q = quoteIdent(dbType, schema);
  if (dbType === 'postgres' || dbType === 'duckdb') return `-- SET search_path TO ${q};\n\n`;
  if (dbType === 'mysql' || dbType === 'mariadb' || dbType === 'mssql' || dbType === 'clickhouse' || dbType === 'trino') return `-- USE ${q};\n\n`;
  if (dbType === 'oracle') return `-- ALTER SESSION SET CURRENT_SCHEMA = ${q};\n\n`;
  return '';
}

export function createViewSQL(dbType: string, schema: string): string {
  return `CREATE VIEW ${qualified(dbType, schema, 'new_view')} AS\nSELECT *\nFROM ${qualified(dbType, schema, 'table_name')};`;
}

export function createMaterializedViewSQL(dbType: string, schema: string): string {
  if (dbType === 'clickhouse') {
    return `CREATE MATERIALIZED VIEW ${qualified(dbType, schema, 'new_mv')}\nENGINE = MergeTree ORDER BY tuple()\nAS SELECT *\nFROM ${qualified(dbType, schema, 'table_name')};`;
  }
  return `CREATE MATERIALIZED VIEW ${qualified(dbType, schema, 'new_mv')} AS\nSELECT *\nFROM ${qualified(dbType, schema, 'table_name')};`;
}

export function createFunctionSQL(dbType: string, schema: string): string {
  const name = qualified(dbType, schema, 'new_function');
  switch (dbType) {
    case 'mysql':
    case 'mariadb':
      return `CREATE FUNCTION ${name}(a INT, b INT)\nRETURNS INT DETERMINISTIC\nRETURN a + b;`;
    case 'mssql':
      return `CREATE FUNCTION ${name}(@a INT, @b INT)\nRETURNS INT\nAS\nBEGIN\n  RETURN @a + @b;\nEND;`;
    case 'oracle':
      return `CREATE OR REPLACE FUNCTION ${name}(a NUMBER, b NUMBER)\nRETURN NUMBER IS\nBEGIN\n  RETURN a + b;\nEND;\n/`;
    case 'duckdb':
      return `CREATE MACRO ${name}(a, b) AS a + b;`;
    default:
      return `CREATE OR REPLACE FUNCTION ${name}(a integer, b integer)\nRETURNS integer\nLANGUAGE sql\nAS $$\n  SELECT a + b\n$$;`;
  }
}

export function createProcedureSQL(dbType: string, schema: string): string {
  const name = qualified(dbType, schema, 'new_procedure');
  switch (dbType) {
    case 'mysql':
    case 'mariadb':
      return `CREATE PROCEDURE ${name}()\nBEGIN\n  SELECT 1;\nEND;`;
    case 'mssql':
      return `CREATE PROCEDURE ${name}\nAS\nBEGIN\n  SELECT 1;\nEND;`;
    case 'oracle':
      return `CREATE OR REPLACE PROCEDURE ${name} IS\nBEGIN\n  NULL;\nEND;\n/`;
    default:
      return `CREATE OR REPLACE PROCEDURE ${name}()\nLANGUAGE sql\nAS $$\n  SELECT 1\n$$;`;
  }
}

export function createSequenceSQL(dbType: string, schema: string): string {
  return `CREATE SEQUENCE ${qualified(dbType, schema, 'new_sequence')} START WITH 1 INCREMENT BY 1;`;
}
